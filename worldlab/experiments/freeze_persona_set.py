"""Freeze persona_set_v1 from Reproducibility Gate 0 runs.

Numerical traits come from the Python RNG. A behavioral profile is the unique
modal profile across source runs. If there is no unique mode, the first
schema-valid profile is kept and ambiguity_flag is true.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from agents.persona_generator import generate_traits, write_json
from config.settings import PROJECT_ROOT, get_settings
from experiments.reproducibility_check import canonical_sha256, file_sha256
from models.schemas import TRAIT_NAMES, AgentTraits, BehavioralProfile

PERSONA_SET_VERSION = "persona_set_v1"
CANONICALIZATION_RULE = (
    "Numerical traits are regenerated by Python random.Random from master_seed and "
    "agent_index. Those traits are the only authoritative trait source. "
    "Among schema-valid behavioral profiles from the source runs, in source-run order, "
    "use the unique modal profile when one profile is strictly more frequent than every "
    "other profile. If there is no unique mode, use the first schema-valid profile and "
    "set ambiguity_flag true."
)
GATE0_SUMMARY = (
    PROJECT_ROOT / "data" / "reproducibility" / "repro_gate0_20260926T063341Z" / "summary.json"
)


def persona_content_payload(agent_id: str, traits: dict[str, float], profile: dict[str, Any]) -> dict[str, Any]:
    return {"agent_id": agent_id, "traits": traits, "profile": profile}


def select_modal_profile(
    profiles: list[dict[str, Any]],
) -> tuple[dict[str, Any], bool, int]:
    if not profiles:
        raise ValueError("no schema-valid profiles")
    keys = [canonical_sha256(profile) for profile in profiles]
    counts = Counter(keys)
    best_count = max(counts.values())
    modes = [key for key, count in counts.items() if count == best_count]
    if len(modes) == 1 and best_count >= 2:
        chosen = next(profile for profile, key in zip(profiles, keys, strict=True) if key == modes[0])
        return chosen, False, best_count
    return profiles[0], True, best_count


def freeze_persona_set(
    run_dirs: list[Path],
    output_dir: Path,
    *,
    master_seed: int,
    llm_seed: int,
    model: str,
    prompt_version: str,
    source_run_ids: list[str],
) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest_agents: list[dict[str, Any]] = []
    agent_ids = _shared_agent_ids(run_dirs)
    for agent_id in agent_ids:
        record = _canonicalize_agent(
            agent_id,
            run_dirs,
            master_seed=master_seed,
            source_run_ids=source_run_ids,
            prompt_version=prompt_version,
        )
        path = output_dir / f"{agent_id}.json"
        write_json(path, record)
        manifest_agents.append(
            {
                "agent_id": agent_id,
                "ambiguity_flag": record["ambiguity_flag"],
                "modal_profile_count": record["modal_profile_count"],
                "traits_sha256": record["traits_sha256"],
                "profile_sha256": record["profile_sha256"],
                "persona_content_sha256": record["persona_content_sha256"],
                "file_sha256": file_sha256(path),
            }
        )
    manifest = {
        "persona_set_version": PERSONA_SET_VERSION,
        "source_run_ids": source_run_ids,
        "canonicalization_rule": CANONICALIZATION_RULE,
        "model": model,
        "prompt_version": prompt_version,
        "master_seed": master_seed,
        "llm_seed": llm_seed,
        "agents": manifest_agents,
    }
    write_json(output_dir / "manifest.json", manifest)
    return output_dir


def freeze_gate0(summary_path: Path = GATE0_SUMMARY) -> Path:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    settings = summary["settings"]
    source_run_ids = list(summary["run_ids"])
    run_dirs = [get_settings().personas_dir / run_id for run_id in source_run_ids]
    return freeze_persona_set(
        run_dirs,
        get_settings().personas_dir / PERSONA_SET_VERSION,
        master_seed=int(settings["master_seed"]),
        llm_seed=int(settings["llm_seed"]),
        model=str(settings["model"]),
        prompt_version=str(settings["prompt_version"]),
        source_run_ids=source_run_ids,
    )


def _canonicalize_agent(
    agent_id: str,
    run_dirs: list[Path],
    *,
    master_seed: int,
    source_run_ids: list[str],
    prompt_version: str,
) -> dict[str, Any]:
    profiles: list[dict[str, Any]] = []
    agent_index: int | None = None
    for run_dir in run_dirs:
        payload = json.loads((run_dir / f"{agent_id}.json").read_text(encoding="utf-8"))
        if agent_index is None:
            agent_index = int(payload["agent_index"])
        elif int(payload["agent_index"]) != agent_index:
            raise RuntimeError(f"{agent_id} agent_index differs across source runs")
        try:
            profile = BehavioralProfile.model_validate(payload["behavioral_profile"]).model_dump()
        except ValidationError as exc:
            raise RuntimeError(f"{run_dir.name} {agent_id} profile failed schema") from exc
        profiles.append(profile)
    if agent_index is None:
        raise RuntimeError(f"{agent_id} is missing")
    traits, trait_seed = generate_traits(master_seed, agent_index)
    _require_source_traits_match(agent_id, run_dirs, traits)
    profile, ambiguity_flag, modal_count = select_modal_profile(profiles)
    trait_payload = {name: getattr(traits, name) for name in TRAIT_NAMES}
    content = persona_content_payload(agent_id, trait_payload, profile)
    return {
        "agent_id": agent_id,
        "agent_index": agent_index,
        "persona_set_version": PERSONA_SET_VERSION,
        "ambiguity_flag": ambiguity_flag,
        "trait_source": "python_rng",
        "trait_seed": trait_seed,
        "traits": trait_payload,
        "profile_source": "llm",
        "behavioral_profile": profile,
        "prompt_version": prompt_version,
        "canonicalization_rule": CANONICALIZATION_RULE,
        "source_run_ids": source_run_ids,
        "modal_profile_count": modal_count,
        "traits_sha256": canonical_sha256(trait_payload),
        "profile_sha256": canonical_sha256(profile),
        "persona_content_sha256": canonical_sha256(content),
    }


def _require_source_traits_match(agent_id: str, run_dirs: list[Path], traits: AgentTraits) -> None:
    expected = canonical_sha256({name: getattr(traits, name) for name in TRAIT_NAMES})
    for run_dir in run_dirs:
        payload = json.loads((run_dir / f"{agent_id}.json").read_text(encoding="utf-8"))
        observed = AgentTraits.model_validate(payload["traits"])
        observed_hash = canonical_sha256({name: getattr(observed, name) for name in TRAIT_NAMES})
        if observed_hash != expected:
            raise RuntimeError(f"{run_dir.name} {agent_id} traits differ from the Python RNG")


def _shared_agent_ids(run_dirs: list[Path]) -> list[str]:
    sets = [{path.stem for path in run_dir.glob("agent_*.json")} for run_dir in run_dirs]
    if not sets or any(item != sets[0] for item in sets[1:]):
        raise RuntimeError("source runs do not contain identical agent IDs")
    return sorted(sets[0])


def main() -> None:
    output = freeze_gate0()
    print(f"persona_set_v1={output}")


if __name__ == "__main__":
    if __package__ is None:
        raise SystemExit("請在 worldlab 目錄執行：python -m experiments.freeze_persona_set")
    main()
